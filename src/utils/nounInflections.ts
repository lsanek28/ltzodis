/**
 * Extracts the primary head noun from Ukrainian and English dictionary strings,
 * stripping explanatory parentheticals like "будинок (дім)" -> "будинок"
 */
export function extractPrimaryWord(raw: string): string {
  if (!raw) return '';
  const normalized = raw.replace(/bus\/tram stop/gi, 'bus stop');
  const cleaned = normalized.split(/[(,]|\s+\/\s+/)[0].trim().toLowerCase();
  return cleaned;
}


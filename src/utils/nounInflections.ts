/**
 * Applies Ukrainian consonant mutation for dative/locative (рука -> руці, нога -> нозі, муха -> мусі)
 */
function applyConsonantMutation(stem: string): string {
  if (stem.endsWith('к')) return stem.slice(0, -1) + 'ц';
  if (stem.endsWith('г')) return stem.slice(0, -1) + 'з';
  if (stem.endsWith('х')) return stem.slice(0, -1) + 'с';
  return stem;
}


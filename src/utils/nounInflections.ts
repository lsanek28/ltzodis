/**
 * Returns the plural form of an English noun
 */
export function getEnglishPlural(base: string): string {
  const lower = base.trim().toLowerCase();
  if (ENGLISH_IRREGULAR_PLURALS[lower]) {
    return ENGLISH_IRREGULAR_PLURALS[lower];
  }
  if (lower.endsWith(' child')) {
    return lower.slice(0, -6) + ' children';
  }
  if (lower.endsWith(' woman')) {
    return lower.slice(0, -6) + ' women';
  }
  if (lower.endsWith(' man')) {
    return lower.slice(0, -4) + ' men';
  }
  if (lower.endsWith(' person')) {
    return lower.slice(0, -7) + ' people';
  }
  if (lower.endsWith(' people')) {
    return lower;
  }
  if (lower.endsWith('y') && !/[aeiou]y$/.test(lower)) {
    return lower.slice(0, -1) + 'ies';
  }
  if (/(s|ss|sh|ch|x|z)$/.test(lower)) {
    return lower + 'es';
  }
  if (lower.endsWith('fe')) {
    return lower.slice(0, -2) + 'ves';
  }
  return lower + 's';
}

/**
 * Inflects an English noun phrase with the appropriate prepositional / syntactical case marker
 */
export function inflectEnglishNoun(
  noun: NounEntry,
  grammaticalCase: GrammaticalCase,
  number: GrammaticalNumber
): string {
  const rawEn = noun.en || '';
  const head = extractPrimaryWord(rawEn);
  if (!head) return rawEn;

  const word = number === 'sg' ? head : getEnglishPlural(head);

  switch (grammaticalCase) {
    case 'nom':
      return word;
    case 'gen':
      return `of the ${word}`;
    case 'dat':
      return `to/for the ${word}`;
    case 'acc':
      return `the ${word}`;
    case 'ins':
      return `with/by the ${word}`;
    case 'loc':
      return `in/at the ${word}`;
    case 'voc':
      return `O ${word}!`;
  }
}

/**
 * Main translation retrieval function: returns the localized inflected word for any case & number
 */
export function getNounTranslationInCase(
  noun: NounEntry,
  grammaticalCase: GrammaticalCase,
  number: GrammaticalNumber,
  language: AppLanguage
): { primary: string; secondary?: string } {
  const ukForm = inflectUkrainianNoun(noun, grammaticalCase, number);
  const enForm = inflectEnglishNoun(noun, grammaticalCase, number);

  if (language === 'uk') {
    return { primary: ukForm, secondary: enForm };
  } else if (language === 'en') {
    return { primary: enForm, secondary: ukForm };
  } else {
    return { primary: ukForm, secondary: enForm };
  }
}

